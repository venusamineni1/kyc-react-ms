-- Append-only audit trail of every real request/response exchanged with NRTS
-- (submit, status polls, alert details, document fetches). RequestPayload/ResponsePayload
-- are encrypted at the application layer (PiiCryptoService) before being stored here.
CREATE TABLE IF NOT EXISTS ScreeningNrtsInteractions (
    InteractionID      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ScreeningLogID     BIGINT, -- nullable: some calls (e.g. document fetch) have no reliable correlation key
    ClientID           BIGINT,
    ExternalRequestID  VARCHAR(100),
    NrtsProcessId      BIGINT,
    NrtsReqId          BIGINT,
    InteractionType    VARCHAR(30) NOT NULL, -- SUBMIT | STATUS_POLL | ALERT_DETAILS | DOCUMENT_FETCH
    HttpStatus         INT,
    RequestPayload     TEXT,                 -- encrypted
    ResponsePayload    TEXT,                 -- encrypted
    IsFinal            BOOLEAN DEFAULT FALSE,
    CreatedAt          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ScreeningLogID) REFERENCES ScreeningLogs(LogID)
);
CREATE INDEX IF NOT EXISTS idx_nrts_interactions_logid ON ScreeningNrtsInteractions(ScreeningLogID);
CREATE INDEX IF NOT EXISTS idx_nrts_interactions_processid ON ScreeningNrtsInteractions(NrtsProcessId);

