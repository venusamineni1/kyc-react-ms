ALTER TABLE BatchRuns ADD COLUMN IF NOT EXISTS RunGroupId VARCHAR(64);

-- Mass Screening: tracks a single 700K-client run across all sub-batches
CREATE TABLE IF NOT EXISTS BatchScreeningRuns (
    Id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RunGroupId         VARCHAR(64) NOT NULL UNIQUE,
    FileName           VARCHAR(255),
    SystemId           VARCHAR(100),
    TotalClientCount   BIGINT,
    TotalBatches       INT,
    BatchesCompleted   INT DEFAULT 0,
    OverallStatus      VARCHAR(20) DEFAULT 'DETECTED',
    PersistClients     BOOLEAN DEFAULT FALSE,
    CallbackWebhookUrl VARCHAR(1000),
    ErrorMessage       TEXT,
    CreatedAt          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CompletedAt        TIMESTAMP
);

-- Mass Screening staging: full client data buffered for persist-first mode (Mode B)
-- PII columns (FirstName, MiddleName, LastName, NameAtBirth, NickName, DateOfBirth, IdNumber,
-- AddressLine1, PlaceOfBirth, CityOfBirth) are encrypted at the application layer
-- (PiiCryptoService) before being stored — widened to TEXT to hold ciphertext, and
-- DateOfBirth changed from DATE to TEXT since the encrypted value is no longer a SQL date.
CREATE TABLE IF NOT EXISTS BatchScreeningStaging (
    Id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RunGroupId             VARCHAR(64) NOT NULL,
    ClientId               BIGINT,
    TitlePrefix            VARCHAR(50),
    FirstName              TEXT,                 -- encrypted
    MiddleName             TEXT,                 -- encrypted
    LastName               TEXT,                 -- encrypted
    TitleSuffix            VARCHAR(50),
    Citizenship1           VARCHAR(100),
    Citizenship2           VARCHAR(100),
    OnboardingDate         DATE,
    Status                 VARCHAR(20),
    NameAtBirth            TEXT,                 -- encrypted
    NickName               TEXT,                 -- encrypted
    Gender                 VARCHAR(10),
    DateOfBirth            TEXT,                 -- encrypted (was DATE)
    Language               VARCHAR(50),
    Occupation             VARCHAR(255),
    CountryOfTax           VARCHAR(100),
    SourceOfFundsCountry   VARCHAR(100),
    FatcaStatus            VARCHAR(50),
    CrsStatus              VARCHAR(50),
    AddressLine1           TEXT,                 -- encrypted
    City                   VARCHAR(255),
    ZipCode                VARCHAR(50),
    Province               VARCHAR(255),
    Country                VARCHAR(100),
    Nationality            VARCHAR(100),
    LegDocType             VARCHAR(100),
    IdNumber               TEXT,                 -- encrypted
    PlaceOfBirth           TEXT,                 -- encrypted
    CityOfBirth            TEXT,                 -- encrypted
    CountryOfBirth         VARCHAR(100),
    ProcessingStatus       VARCHAR(20) DEFAULT 'PENDING',
    CreatedAt              TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
